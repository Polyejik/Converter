#!/usr/bin/env python3
"""Build a deterministic finance seed from existing local D1 assignments.

Run from any directory: python3 tools/build_finance_seed.py
Requires the existing migrated demo database; never creates entities or assignments.
Only Python standard-library modules are used. Wrangler supplies local D1 access.
IDs belong to the finance-v1 namespace; conflict handling never replaces other rows.
"""
import hashlib
import json
import subprocess
from collections import defaultdict
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'api/seed/0002_finance.sql'
BASE = ['npx', 'wrangler', 'd1', 'execute', 'portfolio-pulse', '--local',
        '--config', 'api/wrangler.jsonc']


def query(sql):
    result = subprocess.run(BASE + ['--command', sql, '--json'], cwd=ROOT,
                            check=True, capture_output=True, text=True)
    data = json.loads(result.stdout)
    if not all(item.get('success') for item in data):
        raise RuntimeError(data)
    return [item['results'] for item in data]


def rule(value):
    return int.from_bytes(hashlib.sha256(value.encode()).digest()[:8], 'big')


def quote(value):
    if value is None:
        return 'NULL'
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def insert(table, columns, values):
    return (f"INSERT INTO {table} ({','.join(columns.split())}) VALUES "
            f"({','.join(map(quote, values))}) ON CONFLICT(tenant_id,id) DO NOTHING;")


def main():
    projects, members = query("SELECT id FROM projects WHERE tenant_id='demo' ORDER BY id; "
        "SELECT m.project_id,m.user_id,s.hourly_rate_usd FROM project_members m "
        "JOIN staff_profiles s ON s.tenant_id=m.tenant_id AND s.user_id=m.user_id "
        "JOIN users u ON u.tenant_id=s.tenant_id AND u.id=s.user_id "
        "WHERE m.tenant_id='demo' AND u.role='specialist' AND u.active=1 "
        "ORDER BY m.project_id,m.user_id;")
    if len(projects) != 30:
        raise SystemExit('Expected 30 existing demo projects; seed existing entities first if absent.')
    assigned = defaultdict(list)
    for member in members:
        assigned[member['project_id']].append(member)
    selected = {}
    by_user = defaultdict(list)
    for project in projects:
        pid = project['id']
        selected[pid] = assigned[pid][:4]
        if not 2 <= len(selected[pid]) <= 4:
            raise SystemExit(f'{pid}: requires 2–4 existing assigned active specialists')
        for member in selected[pid]:
            by_user[member['user_id']].append(pid)
    lines = ['-- Generated by tools/build_finance_seed.py from actual local D1 entities.',
             '-- SHA-256 ID rules; fixed dates; receipt refunds have positive amounts.',
             '-- Each specialist weekly budget is divided across all selected assignments.',
             '-- Existing rows are preserved; no transaction statements.']
    total = 0
    for index, project in enumerate(projects):
        pid = project['id']
        h = rule(pid)
        count = 3 + h % 4
        budget = 500000 + (h // 4) % 150001
        total += budget
        for number in range(count):
            amount = budget // count + (number < budget % count)
            assert 80000 <= amount <= 900000
            iid = f'finance-v1:invoice:{pid}:{number + 1}'
            issued = date(2026, 1, 5) + timedelta(days=14 * number)
            lines.append(insert('invoices',
                'id tenant_id project_id invoice_no amount_usd invoice_date due_date status updated_at',
                [iid, 'demo', pid, f'FIN-V1-{pid}-{number + 1}', amount,
                 issued.isoformat(), (issued + timedelta(days=30)).isoformat(), 'issued', '2026-03-02T00:00:00Z']))
            # Leave the final stage unpaid; spread 63% of the project budget
            # across the other stages, without exceeding an invoice's amount.
            paid_total = budget * 63 // 100
            paid = paid_total // (count - 1) + (number < paid_total % (count - 1))
            if number < count - 1:
                lines.append(insert('receipts', 'id tenant_id invoice_id amount_usd kind paid_on note updated_at',
                    [f'finance-v1:receipt:{pid}:{number + 1}', 'demo', iid, paid, 'receipt',
                     (issued + timedelta(days=21)).isoformat(), 'Finance demo receipt', '2026-03-02T00:00:00Z']))
            if index in (0, 15) and number == 0:
                lines.append(insert('receipts', 'id tenant_id invoice_id amount_usd kind paid_on note updated_at',
                    [f'finance-v1:refund:{pid}', 'demo', iid, 5000, 'refund', '2026-03-02',
                     'Finance demo refund', '2026-03-02T00:00:00Z']))
    assert 15000000 <= total <= 20000000
    for uid, pids in sorted(by_user.items()):
        for week in range(8):
            # Quarter-hour units keep exact SQLite sums; weekly totals are 24–40h.
            units = 96 + rule(f'{uid}:{week}') % 65
            for position, pid in enumerate(sorted(pids)):
                hours = (units // len(pids) + (position < units % len(pids))) / 4
                member = next(m for m in selected[pid] if m['user_id'] == uid)
                activity = ['technical', 'report_processing', 'client_meetings', 'economic'][rule(pid) % 4]
                lines.append(insert('time_entries',
                    'id tenant_id user_id project_id week_start activity hours note status rate_snapshot_usd updated_at',
                    [f'finance-v1:time:{pid}:{uid}:{week + 1}', 'demo', uid, pid,
                     (date(2026, 1, 5) + timedelta(weeks=week)).isoformat(), activity, hours,
                     'Finance demo fixed eight-week allocation', 'approved', member['hourly_rate_usd'],
                     '2026-03-02T00:00:00Z']))
    ids = ','.join(quote(p['id']) for p in projects)
    sums = "(SELECT COALESCE(SUM(i.amount_usd),0) FROM invoices i WHERE i.tenant_id=projects.tenant_id AND i.project_id=projects.id)"
    lines.append(f"UPDATE projects SET contract_amount_usd={sums}, version=version+1 "
                 f"WHERE tenant_id='demo' AND id IN ({ids}) AND contract_amount_usd <> {sums};")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{OUT.relative_to(ROOT)}: {total:,} USD; {len(by_user)} specialists')


if __name__ == '__main__':
    main()
